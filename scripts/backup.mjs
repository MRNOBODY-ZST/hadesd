import { spawn } from 'node:child_process';
import { createWriteStream } from 'node:fs';
import { mkdir, cp, readFile, writeFile, stat } from 'node:fs/promises';
import { directoryIntegrity, fileSha256 } from './file-integrity.mjs';
import { exportS3Media } from './storage-backup.mjs';
import path from 'node:path';
import { pipeline } from 'node:stream/promises';
const root=path.resolve(import.meta.dirname,'..');
const storageMode=process.env.STORAGE_MODE||'local';
if(!['local','s3'].includes(storageMode))throw new Error('STORAGE_MODE must be local or s3');
const destination=path.join(root,'.local/backups',new Date().toISOString().replaceAll(':','-'));
await mkdir(destination,{recursive:true,mode:0o700});
const releaseRoot=process.env.RELEASE_ROOT;
const before=await readFile(path.join(releaseRoot,'current/manifest.json'),'utf8').catch(()=>null);
const output=path.join(destination,'database.sql');
const child=spawn('docker',['compose','--env-file','.env','-f','infra/compose/dependencies.yaml','exec','-T','-e','MYSQL_PWD','mysql','mysqldump','-u',process.env.DB_USERNAME,'--single-transaction','--no-tablespaces','--routines','--triggers',process.env.DB_NAME],{cwd:root,env:{...process.env,MYSQL_PWD:process.env.DB_PASSWORD},stdio:['ignore','pipe','pipe']});
let diagnostic='';child.stderr.on('data',b=>{diagnostic=(diagnostic+b).slice(-1000);});
const done=new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',code=>code===0?resolve():reject(new Error(`Database backup failed (${code})`)));});
await Promise.all([pipeline(child.stdout,createWriteStream(output,{mode:0o600})),done]);
let storage={mode:storageMode};
if(storageMode==='s3')storage={...storage,export:await exportS3Media(path.join(destination,'media'),path.join(destination,'storage-export.json'))};
else await cp(process.env.MEDIA_ROOT,path.join(destination,'media'),{recursive:true});
await cp(releaseRoot,path.join(destination,'published'),{recursive:true,verbatimSymlinks:true,filter:source=>!source.startsWith(path.join(releaseRoot,'work'))&&!source.startsWith(path.join(releaseRoot,'staging'))});
const after=await readFile(path.join(releaseRoot,'current/manifest.json'),'utf8').catch(()=>null);
if(before!==after)throw new Error('Release changed during backup; pause publication and run backup again. This directory is incomplete.');
await cp(path.join(root,'.env'),path.join(destination,'config.env'));
const databaseHash=await fileSha256(output);
const media=await directoryIntegrity(path.join(destination,'media'));
const published=await directoryIntegrity(path.join(destination,'published'));
await writeFile(path.join(destination,'backup.json'),JSON.stringify({createdAt:new Date().toISOString(),release:before?JSON.parse(before):null,databaseSha256:databaseHash,databaseBytes:(await stat(output)).size,storage,integrity:{media,published}},null,2),{mode:0o600});
console.log(`Backup verified: ${destination}`);
